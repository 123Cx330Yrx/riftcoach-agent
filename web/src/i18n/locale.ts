export interface ProductCatalogs {
  readonly en: Readonly<Record<string, string>>
  readonly "zh-CN": Readonly<Record<string, string>>
}

const productCatalogs: ProductCatalogs = {
  en: enCatalog,
  "zh-CN": zhCnCatalog,
}

function isUiLocale(value: unknown): value is UiLocale {
  return value === "zh-CN" || value === "en"
}

function decodeStoredLocale(value: string): UiLocale | undefined {
  try {
    const parsed = JSON.parse(value) as unknown
    if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) return undefined
    const row = parsed as Record<string, unknown>
    const keys = Object.keys(row).sort()
    if (keys.length !== 2 || keys[0] !== "locale" || keys[1] !== "schema_version") return undefined
    if (row.schema_version !== "1.0" || !isUiLocale(row.locale)) return undefined
    return row.locale
  } catch {
    return undefined
  }
}

export class BrowserLocaleStore implements LocaleStore {
  private readonly storage: LocaleStorage | undefined

  constructor(storage?: LocaleStorage) {
    this.storage = storage ?? resolveBrowserStorage()
  }

  read(): UiLocale | undefined {
    if (this.storage === undefined) return undefined
    try {
      const value = this.storage.getItem(UI_LOCALE_STORAGE_KEY)
      return value === null ? undefined : decodeStoredLocale(value)
    } catch {
      return undefined
    }
  }

  write(locale: UiLocale): void {
    if (this.storage === undefined) return
    try {
      this.storage.setItem(
        UI_LOCALE_STORAGE_KEY,
        JSON.stringify({ schema_version: "1.0", locale }),
      )
    } catch {
      // Locale persistence is optional; product loading must remain available.
    }
  }
}

function resolveBrowserStorage(): LocaleStorage | undefined {
  if (typeof window === "undefined") return undefined
  try {
    return window.localStorage
  } catch {
    return undefined
  }
}

function localeFromLanguages(languages: readonly string[]): UiLocale {
  for (const language of languages) {
    const normalized = language.toLowerCase()
    if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN"
    if (normalized === "en" || normalized.startsWith("en-")) return "en"
  }
  return "en"
}

export function resolveUiLocale(
  store: LocaleStore,
  navigatorLanguages: readonly string[] = [],
): UiLocale {
  try {
    const stored = store.read()
    if (stored !== undefined) return stored
  } catch {
    // A custom store must not be able to block product rendering.
  }
  return localeFromLanguages(navigatorLanguages)
}

type MessageParameter = string | number

function interpolate(template: string, params: Readonly<Record<string, MessageParameter>>): string {
  return template.replace(/\{\{([a-zA-Z0-9_]+)\}\}/g, (placeholder, key: string) => {
    const value = params[key]
    return value === undefined ? placeholder : String(value)
  })
}

export function translate(
  locale: UiLocale,
  key: string,
  params: Readonly<Record<string, MessageParameter>> = {},
  catalogs: ProductCatalogs = productCatalogs,
): string {
  const template = catalogs[locale][key] ?? catalogs.en[key] ?? key
  return interpolate(template, params)
}
